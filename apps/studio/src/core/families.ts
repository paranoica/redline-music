export function effectInfo(effect: string): EffectInfo {
  const known = TABLE[effect];
  if (!known) return { family: "Прочее", label: effect, internal: false };
  return { family: known[0], label: known[1], internal: known[0] === "Цепочка" };
}

export function addable(effects: readonly EffectSpec[]): EffectSpec[] {
  return effects.filter((e) => !effectInfo(e.effect).internal);
}

